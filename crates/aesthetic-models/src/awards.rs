    #[test]
    fn test_award_registry_lookup() {
        let m1 = find_award_match("Oppenheimer (2023)", Some(2023));
        assert!(m1.is_some());
        assert_eq!(m1.unwrap().cinematographer, "Hoyte van Hoytema");

        let m2 = find_award_match("dune part two", None);
        assert!(m2.is_some());
        assert_eq!(m2.unwrap().cinematographer, "Greig Fraser");

        let m3 = find_award_match("West Side Story", Some(2021));
        assert!(m3.is_some());
        assert_eq!(m3.unwrap().cinematographer, "Janusz Kamiński");

        let m4 = find_award_match("Barry Lyndon (1975)", Some(1975));
        assert!(m4.is_some());
        assert_eq!(m4.unwrap().cinematographer, "John Alcott");
    }
