/// Attempts to find a matching award record using fuzzy normalized title and optional release year.
pub fn find_award_match(
    query_title: &str,
    query_year: Option<u32>,
) -> Option<&'static AwardRecord> {
    let norm_query = normalize_title(query_title);
    if norm_query.is_empty() {
        return None;
    }

    // Exact match with year check (allowing +/- 1 year release date shift)
    if let Some(year) = query_year {
        for record in CINEMATOGRAPHY_AWARDS_REGISTRY {
            if (record.year as i32 - year as i32).abs() <= 1
                && normalize_title(record.title) == norm_query
            {
                return Some(record);
            }
        }
    }

    // Exact title match (if year is provided, enforce <= 3 years difference to avoid matching remakes)
    for record in CINEMATOGRAPHY_AWARDS_REGISTRY {
        let norm_rec = normalize_title(record.title);
        if norm_rec == norm_query {
            if let Some(year) = query_year {
                if (record.year as i32 - year as i32).abs() <= 3 {
                    return Some(record);
                }
            } else {
                return Some(record);
            }
        }
    }

    // Substring / containment match
    for record in CINEMATOGRAPHY_AWARDS_REGISTRY {
        let norm_rec = normalize_title(record.title);
        if norm_rec.len() >= 4 && (norm_query.contains(&norm_rec) || norm_rec.contains(&norm_query))
        {
            if let Some(year) = query_year {
                if (record.year as i32 - year as i32).abs() <= 2 {
                    return Some(record);
                }
            } else {
                return Some(record);
            }
        }
    }

    None
}

