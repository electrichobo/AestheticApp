//! Cinematography Awards & Historical Landmark Registry (1995 – 2025+)
//!
//! Canonical database of Academy Award (Oscar), American Society of Cinematographers (ASC),
//! and British Society of Cinematographers (BSC) winners and nominees for Best Cinematography,
//! supplemented by historical landmark masterworks.

use serde::Serialize;

/// Detailed record of an award-recognized or historical reference film.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct AwardRecord {
    pub title: &'static str,
    pub year: u32,
    pub cinematographer: &'static str,
    pub director: &'static str,
    pub aspect_ratio: &'static str,
    pub style_family: &'static str,
    pub awards: &'static [&'static str],
}

impl AwardRecord {
    pub const fn new(
        title: &'static str,
        year: u32,
        cinematographer: &'static str,
        director: &'static str,
        aspect_ratio: &'static str,
        style_family: &'static str,
        awards: &'static [&'static str],
    ) -> Self {
        Self {
            title,
            year,
            cinematographer,
            director,
            aspect_ratio,
            style_family,
            awards,
        }
    }
}

/// Normalizes a movie title string for robust fuzzy matching.
pub fn normalize_title(title: &str) -> String {
    title
        .to_lowercase()
        .chars()
        .filter(|c| c.is_alphanumeric() || c.is_whitespace())
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

